import { expect, test } from "bun:test";
import GLib from "gi://GLib?version=2.0";
import Gtk from "gi://Gtk?version=4.0";
import type { Account } from "../models";
import { filters as defaults } from "../models/search";
import { SearchFilters } from "./search-filters";
import { capture, settle, useDisplay } from "./testing";

useDisplay();

const day = (value: string) => {
  const date = GLib.DateTime.new_from_iso8601(value, null);
  if (date === null) throw new Error(`Invalid date ${value}`);
  return date;
};

const dateControls = (filters: SearchFilters) => {
  const picker = filters["from"].get_parent()?.get_last_child();
  const reveal = filters["to"].get_parent()?.get_next_sibling();
  if (!(picker instanceof Gtk.ToggleButton && reveal instanceof Gtk.Revealer)) throw new Error("Date popup has a picker and a calendar revealer");
  const calendar = () => {
    const shown = reveal.get_child();
    if (!(shown instanceof Gtk.Calendar)) throw new Error("Date popup shows a calendar");
    return shown;
  };
  return { picker, reveal, calendar };
};

test("date calendar stays in one popup and restores focus", async () => {
  const filters = new SearchFilters();
  const content = Gtk.Box.new(Gtk.Orientation.VERTICAL, 12);
  content.append(filters.widget);
  const outside = Gtk.Button.new_with_label("Outside date popup");
  outside.set_vexpand(true);
  content.append(outside);
  const window = new Gtk.Window({ title: "Brevlada date popup diagnostic", defaultWidth: 700, defaultHeight: 700, child: content });
  window.present();
  await settle(350);
  const popup = filters["datesButton"].get_popover();
  if (popup === null) throw new Error("Dates button has a popover");
  const { picker, reveal, calendar } = dateControls(filters);
  expect(reveal.get_child()).toBeNull();
  for (const selected of [false, true]) {
    filters["datesButton"].popup();
    await settle(350);
    picker.set_active(true);
    await settle(350);
    expect(calendar().get_ancestor(Gtk.Popover.$gtype)).toBe(popup);
    expect(popup.get_autohide()).toBe(true);
    expect(popup.get_visible()).toBe(true);
    expect(reveal.get_reveal_child()).toBe(true);
    const [, bounds] = calendar().compute_bounds(popup);
    expect(bounds.get_x()).toBeGreaterThanOrEqual(0);
    expect(bounds.get_x() + bounds.get_width()).toBeLessThanOrEqual(popup.get_width());
    expect(filters["from"].get_width()).toBeGreaterThanOrEqual(150);
    if (selected) {
      calendar().select_day(day("2026-10-01T12:00:00Z"));
      await settle(350);
      expect(filters["from"].get_text()).toBe("2026-10-01");
      expect(reveal.get_reveal_child()).toBe(false);
      const focus = window.get_focus();
      expect(focus === filters["from"] || focus?.is_ancestor(filters["from"])).toBe(true);
    } else capture("BREVLADA_DATE_SCREENSHOT", popup, popup);
    popup.popdown();
    await settle(350);
    expect(picker.get_active()).toBe(false);
    expect(reveal.get_reveal_child()).toBe(false);
  }
  window.destroy();
});

test("controls follow the current account and keep custom selections", () => {
  const filters = new SearchFilters();
  const account = (email: string): Account => ({ path: "", email, name: "", host: "", username: "", port: 993, ssl: true, tls: false, oauth2: false, smtp: null });
  const label = (button: Gtk.MenuButton) => button.get_label();
  filters.setAccounts([account("a@example.com"), account("b@example.com")]);
  expect(filters["useCurrent"].get_sensitive()).toBe(false);
  expect(filters.selectedAccounts().size).toBe(2);
  expect(filters["allAccounts"].get_sensitive()).toBe(false);
  expect(label(filters["accountsButton"])).toBe("All accounts");
  expect(filters.accountsFor(null).size).toBe(2);
  expect(filters.accountLabel()).toBe("All accounts");
  expect(label(filters["sourcesButton"])).toBe("All Sources");
  expect(label(filters["datesButton"])).toBe("Any Date");
  expect(filters.folder()).toBeNull();
  expect(filters["useCurrentFolder"].get_sensitive()).toBe(false);
  filters.setCurrentFolder("Archive", false);
  expect(filters["useCurrentFolder"].get_sensitive()).toBe(true);
  filters["useCurrentFolder"].set_active(true);
  expect(filters.folder()).toBe("Archive");
  expect(label(filters["foldersButton"])).toBe("Current Folder");
  filters.keepSelection();
  filters.setCurrentFolder("INBOX", true);
  expect(filters.folder()).toBe("Archive");
  filters["allFolders"].set_active(true);
  expect(filters.folder()).toBeNull();
  filters["useCurrentFolder"].set_active(true);
  expect(filters.folder()).toBe("INBOX");
  filters.setCurrentFolder(null, false);
  expect(filters["useCurrentFolder"].get_sensitive()).toBe(false);
  expect(filters["allFolders"].get_active()).toBe(true);
  expect(filters.folder()).toBeNull();
  expect(filters["useCurrent"].get_sensitive()).toBe(false);
  filters["selected"] = null;
  filters.setCurrent("a@example.com");
  expect(filters.selectedAccounts()).toEqual(new Set(["a@example.com"]));
  expect(filters.filters()).toEqual({ ok: true, value: defaults() });
  expect(filters["useCurrent"].get_sensitive()).toBe(false);
  expect(label(filters["accountsButton"])).toBe("Current Account");
  const second = filters["accountsBox"].get_last_child()?.get_prev_sibling();
  if (!(second instanceof Gtk.CheckButton)) throw new Error("Accounts are check buttons");
  second.set_active(true);
  expect(filters.selectedAccounts().size).toBe(2);
  expect(filters["useCurrent"].get_sensitive()).toBe(true);
  expect(label(filters["accountsButton"])).toBe("All accounts");
  filters.setCurrent("b@example.com");
  expect(filters.selectedAccounts().size).toBe(2);
  const useCurrent = filters["accountsBox"].get_first_child();
  if (!(useCurrent instanceof Gtk.Button)) throw new Error("Accounts start with a button");
  useCurrent.emit("clicked");
  expect(filters.selectedAccounts()).toEqual(new Set(["b@example.com"]));
  expect(filters["useCurrent"].get_sensitive()).toBe(false);
  expect(label(filters["accountsButton"])).toBe("Current Account");
  filters.setAccounts([account("c@example.com"), account("b@example.com"), account("a@example.com")]);
  expect(filters["accounts"]).toEqual(["a@example.com", "b@example.com", "c@example.com"]);
  expect(filters.selectedAccounts()).toEqual(new Set(["b@example.com"]));
  filters.setCurrentFolder("Archive", false);
  filters.resetScope();
  expect(filters.folder()).toBe("Archive");
  filters.keepSelection();
  filters.setCurrentFolder("INBOX", true);
  filters["allAccounts"].emit("clicked");
  filters.resetScope();
  expect(filters.selectedAccounts()).toEqual(new Set(["b@example.com"]));
  expect(filters.folder()).toBe("INBOX");
  filters["allFolders"].set_active(true);
  filters.resetScope();
  expect(filters.folder()).toBe("INBOX");
  filters.setAccounts([account("b@example.com")]);
  expect(label(filters["accountsButton"])).toBe("Current Account");
  filters["sources"][5]?.set_active(false);
  const criteria = filters.filters();
  expect(criteria.ok && criteria.value.sources[5]).toBe(false);
  filters["from"].set_text("2026-10-03");
  filters["to"].set_text("2026-10-02");
  expect(filters.filters().ok).toBe(false);
  expect(filters["dateError"].get_visible()).toBe(true);
  filters["from"].set_text("2026-10-02");
  expect(filters.filters().ok).toBe(true);
  expect(filters["dateError"].get_visible()).toBe(false);
  const { picker, calendar } = dateControls(filters);
  picker.set_active(true);
  calendar().select_day(day("2026-10-01T12:00:00Z"));
  expect(filters["from"].get_text()).toBe("2026-10-01");
  const clear = filters["to"].get_parent()?.get_parent()?.get_last_child();
  if (!(clear instanceof Gtk.Button)) throw new Error("Dates end with a clear button");
  clear.emit("clicked");
  expect(filters.filters()).toEqual({ ok: true, value: defaults({ sources: [true, true, true, true, true, false] }) });
});
