export const BRANDS = new Map([
  ["redditmail.com", "reddit.com"],
  ["twitchmail.com", "twitch.tv"],
  ["meetupmail.com", "meetup.com"],
]);

const canonical = (host: string) => host.trim().replace(/\.+$/, "").toLowerCase();

export function brandOf(host: string) {
  const domain = canonical(host);
  return BRANDS.get(domain) ?? domain;
}

export const isConsumer = (host: string) => CONSUMER.has(canonical(host));
