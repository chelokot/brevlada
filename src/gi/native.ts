const outIndex = { args: ["ptr", "ptr"], returns: "i32" } as const;
const type = { args: ["ptr"], returns: FFIType.u64_fast } as const;
const unit = { args: ["ptr"], returns: "void" } as const;

function library<const Symbols extends Record<string, FFIFunction>>(path: string, symbols: Symbols) {
  return dlopen(path, symbols).symbols as unknown as Typed<Symbols>;
}

