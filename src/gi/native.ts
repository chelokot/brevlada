import { dlopen, FFIType, type FFIFunction, type FFITypeOrString, type Pointer } from "bun:ffi";

type Arg<T> = T extends "ptr" ? Pointer | NodeJS.TypedArray | null : T extends "cstring" ? string | NodeJS.TypedArray | null : number;
type Returned<T> = T extends "ptr" ? Pointer | null : T extends "cstring" ? string : T extends "void" ? void : number;
type Typed<Symbols> = {
  [Name in keyof Symbols]: Symbols[Name] extends { args: infer Args extends readonly FFITypeOrString[]; returns: infer Returns }
    ? (...args: { [Index in keyof Args]: Arg<Args[Index]> }) => Returned<Returns>
    : never;
};

